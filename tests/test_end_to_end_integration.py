import asyncio
import io
import unittest
from unittest.mock import patch

from fastapi import HTTPException, UploadFile
from PIL import Image

from app import main
from scripts.inference_router import RouterResponse
from scripts.label_registry import load_registry, lookup_source


def image_bytes(color=(40, 120, 40), size=(64, 64), image_format="PNG"):
    buffer = io.BytesIO()
    Image.new("RGB", size, color).save(buffer, format=image_format)
    return buffer.getvalue()


def upload(data, filename="leaf.png"):
    return UploadFile(filename=filename, file=io.BytesIO(data))


def router_response(**updates):
    values = {
        "status": "ok",
        "prediction_available": True,
        "selected_model_id": "fixture-model",
        "canonical_disease_id": "apple.apple_scab",
        "display_label": "Apple scab",
        "is_healthy": False,
        "confidence": 0.91,
        "calibration_status": "not_calibrated",
        "abstained": False,
        "abstention_reason": None,
        "ood_warning": None,
        "image_quality_warnings": (),
        "supported_crop_information": ("Apple",),
        "model_selection_reason": "fixture",
        "inference_time_ms": 1.0,
        "warnings": (),
        "error_code": None,
        "user_message": "Prediction generated by a verified model.",
    }
    values.update(updates)
    return RouterResponse(**values)


class FakeRouter:
    def __init__(self, response):
        self.response = response
        self.received = None

    def predict(self, image_data, crop=None):
        self.received = (image_data, crop)
        return self.response


class EndToEndIntegrationTests(unittest.TestCase):
    def call_endpoint(self, data, crop=None, filename="leaf.png"):
        return asyncio.run(main.predict_with_router(upload(data, filename), crop))

    def test_real_upload_reaches_verified_model_and_registry_label(self):
        response = self.call_endpoint(image_bytes())
        self.assertIn(response["status"], {"ok", "uncertain", "unavailable"})
        self.assertIn("canonical_disease_id", response)
        if response["prediction_available"]:
            entries = load_registry()
            matching = [
                entry for entry in entries
                if entry.canonical_id == response["canonical_disease_id"]
            ]
            self.assertEqual(len(matching), 1)
            self.assertEqual(response["display_label"], matching[0].disease)
            self.assertEqual(response["is_healthy"], matching[0].is_healthy)

    def test_diseased_and_healthy_results_preserve_canonical_fields(self):
        diseased = FakeRouter(router_response())
        healthy = FakeRouter(router_response(
            canonical_disease_id="apple.healthy",
            display_label="Healthy",
            is_healthy=True,
            confidence=0.88,
        ))
        with patch.object(main, "router", diseased):
            diseased_result = self.call_endpoint(image_bytes((130, 30, 30)), "Apple")
        with patch.object(main, "router", healthy):
            healthy_result = self.call_endpoint(image_bytes((30, 130, 30)), "Apple")

        self.assertFalse(diseased_result["is_healthy"])
        self.assertEqual(diseased_result["canonical_disease_id"], "apple.apple_scab")
        self.assertTrue(healthy_result["is_healthy"])
        self.assertEqual(healthy_result["canonical_disease_id"], "apple.healthy")
        self.assertEqual(diseased.received[1], "Apple")

    def test_abstention_unclear_image_and_unsupported_crop_are_visible(self):
        abstained = FakeRouter(router_response(
            status="uncertain",
            prediction_available=False,
            canonical_disease_id=None,
            display_label=None,
            confidence=0.42,
            abstained=True,
            abstention_reason="below_validation_threshold",
            image_quality_warnings=("possibly_blurry",),
            error_code="prediction_abstained",
            user_message="The model could not provide a reliable disease classification.",
        ))
        unsupported = FakeRouter(router_response(
            status="unavailable",
            prediction_available=False,
            selected_model_id=None,
            canonical_disease_id=None,
            display_label=None,
            is_healthy=None,
            confidence=None,
            calibration_status=None,
            abstained=True,
            abstention_reason="no_eligible_model",
            supported_crop_information=(),
            error_code="no_eligible_model",
            user_message="No verified model is available for this input.",
        ))
        with patch.object(main, "router", abstained):
            unclear = self.call_endpoint(image_bytes(size=(2, 2)), "Apple")
        with patch.object(main, "router", unsupported):
            unknown = self.call_endpoint(image_bytes(), "Unknown crop")

        self.assertEqual(unclear["status"], "uncertain")
        self.assertTrue(unclear["abstained"])
        self.assertIn("possibly_blurry", unclear["image_quality_warnings"])
        self.assertEqual(unknown["error_code"], "no_eligible_model")
        self.assertFalse(unknown["prediction_available"])

    def test_missing_model_and_server_failure_are_not_successful_predictions(self):
        failure = FakeRouter(router_response(
            status="unavailable",
            prediction_available=False,
            selected_model_id="plantvillage-efficientnetb0-onnx",
            canonical_disease_id=None,
            display_label=None,
            is_healthy=None,
            confidence=None,
            calibration_status=None,
            abstained=True,
            abstention_reason="adapter_inference_failed",
            error_code="adapter_inference_failed",
            user_message="The image could not be safely classified.",
        ))
        with patch.object(main, "router", failure):
            response = self.call_endpoint(image_bytes())
        self.assertEqual(response["status"], "unavailable")
        self.assertFalse(response["prediction_available"])
        self.assertIsNone(response["canonical_disease_id"])
        self.assertEqual(response["error_code"], "adapter_inference_failed")

    def test_upload_validation_rejects_empty_and_oversized_files(self):
        with self.assertRaises(HTTPException) as empty:
            self.call_endpoint(b"")
        self.assertEqual(empty.exception.status_code, 400)

        with self.assertRaises(HTTPException) as oversized:
            self.call_endpoint(b"x" * (main.MAX_UPLOAD_BYTES + 1))
        self.assertEqual(oversized.exception.status_code, 413)

    def test_source_label_registry_round_trip_matches_model_labels(self):
        entries = load_registry()
        for source_label in main.labels:
            entry = lookup_source(entries, "PlantVillage", source_label)
            self.assertIsNotNone(entry, source_label)
            self.assertTrue(entry.canonical_id)
            self.assertTrue(entry.disease)


if __name__ == "__main__":
    unittest.main()
